"""Compile a test against the real source it tests, by slicing that source.

A slice test is a .c/.cpp file whose leading comment names the pieces it needs
from the tree, so the pieces are the ones that ship rather than a copy that
drifts away from them:

  SLICE <file> fn <name> [<name> ...]      one definition each, brace-matched
  SLICE <file> range <start> | <end>       lines from <start> up to (not incl.) <end>
  SLICE <file> define <regex>              every single-line #define it matches
  CFLAGS <flags>                           extra compiler flags for the slice

`<file>` is relative to the repository root, or prefixed `engine ` for a file in
the engine checkout (the QEMU tree the patches in ci/engine-patches apply to).
That prefix is how a device's own code -- hw/arm/s5l8930_i2s.c -- is tested
here.

The rest of the slice file (everything after its leading comment) is the setup:
includes, stub structures, the driver. The generated file is that setup
followed by every extracted piece, in directive order, and it is written to a
temporary directory: neither tree is modified.
"""
import re
from dataclasses import dataclass, field
from pathlib import Path

DIRECTIVE = re.compile(r"^\s*\*\s*(SLICE|CFLAGS|CXXFLAGS|LDLIBS)\b(.*)$")


class SliceError(RuntimeError):
    pass


@dataclass
class Slice:
    path: Path
    setup: str
    defines: list[str] = field(default_factory=list)
    pieces: list[str] = field(default_factory=list)
    sources: list[Path] = field(default_factory=list)
    flags: list[str] = field(default_factory=list)
    ldlibs: list[str] = field(default_factory=list)

    def text(self) -> str:
        names = "\n".join(" *   " + str(source) for source in self.sources)
        header = "/* Generated by tests/slice.py from:\n" + names + "\n */\n"
        return header + "\n".join(self.defines) + "\n" + self.setup + "\n" + "\n".join(self.pieces) + "\n"


def _leading_comment(text: str) -> tuple[str, str]:
    """(the leading block comment, everything after it)."""
    stripped = text.lstrip()
    if not stripped.startswith("/*"):
        return "", text
    end = stripped.index("*/") + 2
    return stripped[:end], stripped[end:]


def _directives(comment: str) -> list[tuple[str, str]]:
    found = []
    for line in comment.splitlines():
        match = DIRECTIVE.match(line)
        if match:
            found.append((match.group(1), match.group(2).strip()))
    return found


def _function(lines: list[str], name: str, path: Path) -> str:
    """One definition, from its signature line through the brace that closes it."""
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*\(")
    for start, line in enumerate(lines):
        if not pattern.search(line) or line.rstrip().endswith(";"):
            continue
        if line.lstrip().startswith(("/*", "*", "//")):
            continue
        depth = 0
        opened = False
        for index in range(start, len(lines)):
            depth += lines[index].count("{") - lines[index].count("}")
            opened = opened or "{" in lines[index]
            if opened and depth == 0:
                return "\n".join(lines[start:index + 1])
        raise SliceError(f"{path}: {name}() has no balanced body")
    raise SliceError(f"{path}: no definition of {name}()")


def _range(lines: list[str], start_text: str, end_text: str, path: Path) -> str:
    start = next((i for i, line in enumerate(lines) if start_text in line), None)
    if start is None:
        raise SliceError(f"{path}: no line matching {start_text!r}")
    end = next((i for i in range(start, len(lines)) if end_text in lines[i]), None)
    if end is None:
        raise SliceError(f"{path}: no line matching {end_text!r} after {start_text!r}")
    return "\n".join(lines[start:end])


def _defines(lines: list[str], pattern: str, path: Path) -> str:
    regex = re.compile(pattern)
    found = [line for line in lines if line.startswith("#define") and regex.search(line)]
    if not found:
        raise SliceError(f"{path}: no #define matching {pattern!r}")
    return "\n".join(found)


def _target(argument: str, root: Path, engine: Path | None, where: Path) -> tuple[Path, str]:
    if argument.startswith("engine "):
        base, rest = engine, argument[len("engine "):]
    else:
        base, rest = root, argument
    if base is None:
        raise SliceError(f"{where}: this slice needs an engine tree: {argument!r}")
    relative = rest.split(" ", 1)[0]
    target = (base / relative).resolve()
    if not target.is_file():
        raise SliceError(f"{where}: {target} does not exist")
    return target, rest[len(relative):].strip()


def build(slice_path: Path, root: Path, engine: Path | None) -> Slice:
    text = slice_path.read_text()
    comment, setup = _leading_comment(text)
    directives = _directives(comment)
    if not directives:
        raise SliceError(f"{slice_path}: no SLICE directives in its leading comment")
    result = Slice(path=slice_path, setup=setup)
    for keyword, argument in directives:
        if keyword == "LDLIBS":
            result.ldlibs.extend(argument.split())
            continue
        if keyword in ("CFLAGS", "CXXFLAGS"):
            result.flags.extend(argument.split())
            continue
        target, command = _target(argument, root, engine, slice_path)
        lines = target.read_text(errors="ignore").splitlines()
        kind, _, arguments = command.partition(" ")
        if kind == "fn":
            for name in arguments.split():
                result.pieces.append(_function(lines, name, target))
        elif kind == "range":
            start_text, _, end_text = arguments.partition("|")
            result.pieces.append(_range(lines, start_text.strip(), end_text.strip(), target))
        elif kind == "define":
            result.defines.append(_defines(lines, arguments.strip(), target))
        else:
            raise SliceError(f"{slice_path}: unknown directive {kind!r}")
        if target not in result.sources:
            result.sources.append(target)
    return result


def generate(slice_path: Path, root: Path, engine: Path | None, output: Path):
    """Write the generated translation unit; return it, its flags and its libraries."""
    piece = build(slice_path, root, engine)
    output.write_text(piece.text())
    return output, piece.flags, piece.ldlibs
